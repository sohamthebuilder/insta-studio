// Build styles/README.md (the style index) from styles/*/style.json and styles/catalog.json.
// usage: node scripts/styles-index.mjs        (run from the repo root, or anywhere)
// It also checks that every style folder has a catalog entry and every catalog entry has a folder.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DIR = path.join(ROOT, "styles");
const catalog = JSON.parse(fs.readFileSync(path.join(DIR, "catalog.json"), "utf8"));
const account = JSON.parse(fs.readFileSync(path.join(ROOT, "account.json"), "utf8"));

const folders = fs.readdirSync(DIR).filter((d) => !d.startsWith("_") && !d.startsWith(".") && fs.existsSync(path.join(DIR, d, "style.json")));
const problems = [];
for (const s of folders) if (!catalog.styles[s]) problems.push(`styles/${s} has no entry in catalog.json`);
for (const s of Object.keys(catalog.styles)) if (!folders.includes(s)) problems.push(`catalog.json lists "${s}" but styles/${s}/style.json is missing`);
for (const s of [account.styles?.default, ...(account.styles?.allowed ?? [])].filter(Boolean))
  if (!folders.includes(s)) problems.push(`account.json styles names "${s}", which is not a style folder`);

const rows = folders.map((s) => {
  const j = JSON.parse(fs.readFileSync(path.join(DIR, s, "style.json"), "utf8"));
  // the look in one sentence: the first "> " line of STYLE.md (style.json's "line" describes the demo film, not the style)
  const quote = (fs.readFileSync(path.join(DIR, s, "STYLE.md"), "utf8").match(/^> (.+)$/m) || [, ""])[1];
  const line = (quote.match(/^.+?[.!?](?=\s|$)/) || [quote])[0].replace(/\*/g, "");
  return { slug: s, name: j.en, group: j.category_en || "Other", line, ...catalog.styles[s] };
});

const ORDER = ["House", "Hand-drawn & Painting", "Cartoon & Anime", "Print & Printmaking", "East Asian Traditions", "Graphic & Type", "Games", "Information & Keynote", "Materials & 3D", "Cinema & Eras", "Evidence Films", "Edit & Documentary"];
const rank = (g) => (ORDER.includes(g) ? ORDER.indexOf(g) : ORDER.length);
const groups = [...new Set(rows.map((r) => r.group))].sort((a, b) => rank(a) - rank(b));

const yes = rows.filter((r) => r.material === "none").length;
let md = `# Style index

<!-- generated by scripts/styles-index.mjs from styles/*/style.json and styles/catalog.json; do not edit by hand -->

${rows.length} styles. ${yes} can be drawn entirely in code; ${rows.length - yes} need real material the owner supplies.
This account's styles (\`account.json\` → \`styles\`): default **${account.styles?.default ?? "storybook"}**, allowed: ${(account.styles?.allowed ?? []).map((s) => `\`${s}\``).join(", ") || "none set"}.

Before using any style read [\`ADAPTING.md\`](ADAPTING.md), then \`styles/<folder>/STYLE.md\`.
Poster sheet to choose from: \`bash studio/render-style-picker.sh [style ...]\` → \`styles/picker/*.jpg\` (no names = every style).

**Renderer:** svg = React/SVG kit · canvas = \`<StyleCanvas>\` 2D · three = \`<StyleCanvas>\` + three.js.
**Material:** – = all drawn in code · real = needs real footage, photos, scans or data.
`;
for (const g of groups) {
  md += `\n## ${g}\n\n| Style | Folder | Renderer | Material | What it is | Note for 9:16 reels |\n|---|---|---|---|---|---|\n`;
  for (const r of rows.filter((x) => x.group === g))
    md += `| ${r.name} | [\`${r.slug}\`](${r.slug}/STYLE.md) | ${r.renderer} | ${r.material === "real" ? "**real**" : "–"} | ${r.line.replace(/\|/g, "/")} | ${(r.note || "").replace(/\|/g, "/")} |\n`;
}
md += `\n## Credits\n\nEvery style except \`storybook\` comes from [lemo-opuscar](${catalog.upstream.repo}) by LemoLab (commit \`${catalog.upstream.commit.slice(0, 7)}\`, imported ${catalog.upstream.imported}). Style guides (\`STYLE.md\`, \`DEMO.md\`, \`style.json\`): MIT, see [\`LICENSE-lemo-opuscar\`](LICENSE-lemo-opuscar). Poster frames (\`poster.jpg\`): CC BY 4.0, © LemoLab, resized to 960 px wide.\n`;

fs.writeFileSync(path.join(DIR, "README.md"), md);
// the same rows as data, for the style picker sheet (studio/src/templates/style-picker.tsx)
const ordered = groups.flatMap((g) => rows.filter((r) => r.group === g));
fs.writeFileSync(
  path.join(DIR, "index.json"),
  JSON.stringify(ordered.map(({ slug, name, group, renderer, material, line }) => ({ slug, name, group, renderer, material, line })), null, 1) + "\n"
);
console.log(`styles/README.md + styles/index.json: ${rows.length} styles in ${groups.length} groups`);
if (problems.length) { console.error(problems.map((p) => "  ! " + p).join("\n")); process.exit(1); }
